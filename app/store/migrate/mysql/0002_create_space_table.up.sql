CREATE TABLE `ops_space` (
	`id` BIGINT NOT NULL  COMMENT 'ID' AUTO_INCREMENT,
	`version` INT NOT NULL COMMENT '版本' DEFAULT '0',
	`name` VARCHAR(255) NOT NULL COLLATE 'utf8mb4_0900_ai_ci' COMMENT '名称',
	`description` TEXT NULL DEFAULT NULL COLLATE 'utf8mb4_0900_ai_ci' COMMENT '描述',
	`createdBy` VARCHAR(255) NOT NULL COMMENT '创建者',
	`created` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
	`updated` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
	`deleted` TINYINT NOT NULL DEFAULT '0' COMMENT '删除标识',
	PRIMARY KEY (`id`) USING BTREE
)
COLLATE='utf8mb4_0900_ai_ci'
ENGINE=InnoDB
;